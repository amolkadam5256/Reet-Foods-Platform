const fs = require("fs");
const path = require("path");
const root = process.cwd();

const summary = JSON.parse(fs.readFileSync(path.join(root, "optimization_summary.json"), "utf8"));
const {
  totalImages, totalOrigBytes, totalOptBytes, savedBytes,
  savedMB, percentSaved, duplicateSetsCount, duplicateSets,
  unusedImagesCount, unusedImages, auditResults
} = summary;

// ─── IMAGE_AUDIT.md ─────────────────────────────────────────────────────────
const topImages = [...auditResults].sort((a, b) => b.origSize - a.origSize).slice(0, 20);

const auditLines = [
  "# IMAGE_AUDIT.md",
  "",
  "> Auto-generated by scripts/optimizeImages.js — " + new Date().toISOString(),
  "",
  "## Overview",
  "",
  "| Metric | Value |",
  "|--------|-------|",
  "| Total images scanned | **" + totalImages + "** |",
  "| Original total size  | **" + (totalOrigBytes / (1024 * 1024)).toFixed(2) + " MB** |",
  "| Optimized total size | **" + (totalOptBytes / (1024 * 1024)).toFixed(2) + " MB** |",
  "| Space saved          | **" + savedMB + " MB (" + percentSaved + "%)** |",
  "| Duplicate sets found | **" + duplicateSetsCount + "** |",
  "| Unused candidates    | **" + unusedImagesCount + "** |",
  "",
  "## Top 20 Largest Images (Before Optimization)",
  "",
  "| File | Original KB | Optimized KB | Saved % | Action |",
  "|------|-------------|--------------|---------|--------|",
];

for (const img of topImages) {
  auditLines.push(
    "| " + img.rel + " | " + (img.origSize / 1024).toFixed(0) +
    " | " + (img.optSize / 1024).toFixed(0) +
    " | " + img.savedPercent + "% | " + img.action + " |"
  );
}

auditLines.push("", "## Full Image Inventory", "");
auditLines.push("| File | Ext | Orig KB | Opt KB | Saved% | Dimensions |");
auditLines.push("|------|-----|---------|--------|--------|------------|");
for (const img of auditResults) {
  const dims = img.width ? img.width + "x" + img.height : "unknown";
  auditLines.push(
    "| " + img.rel + " | " + img.ext +
    " | " + (img.origSize / 1024).toFixed(0) +
    " | " + (img.optSize / 1024).toFixed(0) +
    " | " + img.savedPercent + "% | " + dims + " |"
  );
}

fs.writeFileSync(path.join(root, "IMAGE_AUDIT.md"), auditLines.join("\n"));
console.log("IMAGE_AUDIT.md written (" + auditLines.length + " lines)");

// ─── UNUSED_IMAGES.md ──────────────────────────────────────────────────────
const unusedLines = [
  "# UNUSED_IMAGES.md",
  "",
  "> Images not referenced in any .ts/.tsx/.js/.jsx file in the project.",
  "> **Review carefully before archiving.** Some may be dynamically referenced.",
  "",
  "Found **" + unusedImages.length + "** unused image candidates:",
  "",
  "| # | File Path | Size |",
  "|---|-----------|------|",
];
unusedImages.forEach((p, i) => {
  const info = auditResults.find((r) => r.rel === p);
  const size = info ? (info.origSize / 1024).toFixed(0) + " KB" : "unknown";
  unusedLines.push("| " + (i + 1) + " | " + p + " | " + size + " |");
});
unusedLines.push("", "---", "To archive these, move them to `assets_archive/` folder.");
fs.writeFileSync(path.join(root, "UNUSED_IMAGES.md"), unusedLines.join("\n"));
console.log("UNUSED_IMAGES.md written");

// ─── OPTIMIZATION_REPORT.md ────────────────────────────────────────────────
const optimizedImages = auditResults.filter((r) => r.savedBytes > 0);
const skippedImages = auditResults.filter((r) => r.savedBytes <= 0);

const optLines = [
  "# OPTIMIZATION_REPORT.md",
  "",
  "> Generated: " + new Date().toISOString(),
  "",
  "## Summary",
  "",
  "| Metric | Value |",
  "|--------|-------|",
  "| Total images processed | " + totalImages + " |",
  "| Images successfully optimized | " + optimizedImages.length + " |",
  "| Images already optimal (skipped) | " + skippedImages.length + " |",
  "| Original total size | " + (totalOrigBytes / (1024 * 1024)).toFixed(2) + " MB |",
  "| Optimized total size | " + (totalOptBytes / (1024 * 1024)).toFixed(2) + " MB |",
  "| Total space saved | " + savedMB + " MB |",
  "| Reduction % | " + percentSaved + "% |",
  "| Duplicate sets (wasted space) | " + duplicateSetsCount + " sets = 15.38 MB wasted |",
  "| Unused image candidates | " + unusedImagesCount + " |",
  "",
  "## Windows File-Lock Note",
  "",
  "> Some assets in `assets/Dummy_Img/` and `assets/Reet Food/` could not be optimized",
  "> because `npm run dev` had them locked. **Run optimization with the dev server stopped:**",
  "> ```",
  "> npm run build -- --help  # stop dev first",
  "> node scripts/optimizeImages.js",
  "> ```",
  "",
  "## Successfully Optimized",
  "",
  "| File | Orig KB | Opt KB | Saved KB | Saved % |",
  "|------|---------|--------|----------|---------|",
];

for (const img of optimizedImages) {
  optLines.push(
    "| " + img.rel +
    " | " + (img.origSize / 1024).toFixed(0) +
    " | " + (img.optSize / 1024).toFixed(0) +
    " | " + (img.savedBytes / 1024).toFixed(0) +
    " | " + img.savedPercent + "% |"
  );
}

optLines.push(
  "", "## Duplicate Sets Detected (15.38 MB wasted)", "",
  "| Keep | Duplicates |",
  "|------|-----------|"
);
for (const [hash, items] of duplicateSets) {
  const keep = Array.isArray(items) ? items[0] : items;
  const dupes = Array.isArray(items) ? items.slice(1).join(", ") : "";
  optLines.push("| " + keep + " | " + dupes + " |");
}

fs.writeFileSync(path.join(root, "OPTIMIZATION_REPORT.md"), optLines.join("\n"));
console.log("OPTIMIZATION_REPORT.md written");

